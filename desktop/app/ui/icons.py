def get_pixmap(name: str, size: int = 20, color: str = "#0f172a") -> QPixmap:
    raw = SVG_CATALOG.get(name, SVG_CATALOG["crest"])
    colored_svg = raw.replace("currentColor", color)
    renderer = QSvgRenderer(QByteArray(colored_svg.encode("utf-8")))
    pixmap = QPixmap(size, size)
    pixmap.fill(Qt.transparent)
    painter = QPainter(pixmap)
    renderer.render(painter)
    painter.end()
    return pixmap


def get_icon(name: str, size: int = 20, color: str = "#0f172a") -> QIcon:
    return QIcon(get_pixmap(name, size, color))
